// ============================================================
//  Хитбоксы — пересечение луча с мешами.
//
//  Использует общий RaycastMesh из Raycast3D.h.
//  Возвращает:
//    - hit / distance — как раньше
//    - partIdx        — индекс примитива в меше
//    - damageMult     — множитель урона части тела
// ============================================================

struct HitInfo {
    bool   hit;
    double distance;
    int    partIdx;    // индекс примитива в Mesh
    double damageMult; // множитель урона (1.0 — торс, 2.0 — голова, ...)
};

// Луч (ox,oy) + t*(dx,dy)  против модели игрока.
// Все примитивы модели находятся в её локальной XZ-плоскости,
// а высота — в Y. Мы используем ТОЛЬКО XZ-компоненту луча
// для попадания (плоский shot, без pitch).
//
// Меш для цели строится вызывающей стороной (BuildCharacterMesh)
// и передаётся сюда — это даёт возможность кэшировать его между
// несколькими выстрелами, если нужно.
HitInfo RaycastCharacterMesh(const Mesh& mesh,
    double ox, double oy,
    double dx, double dy);