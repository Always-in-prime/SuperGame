#pragma once
#include "Primitive.h"
#include "Mesh.h"

// ============================================================
//  Единый raycast против примитива/меша.
//
//  Возвращает:
//    - попал ли луч
//    - расстояние вдоль луча (в локальных единицах)
//    - индекс примитива
//    - текстурные координаты u,v в точке попадания
//    - нормаль поверхности (для освещения)
//
//  Луч задан в ЛОКАЛЬНОЙ системе объекта (после трансформации
//  обратно из мировой). То есть вызывающий сам переводит луч.
// ============================================================

struct PrimHit {
    bool   hit;
    double t;         // расстояние вдоль луча
    int    primIdx;   // индекс примитива в Mesh
    double u, v;      // текстурные координаты [0,1)
    double nx, ny, nz;// нормаль
};

// Пересечение луча с одним примитивом.
// Луч: origin + t * dir.
// Возвращает hit=false, если пересечения нет.
PrimHit RaycastPrimitive(const Primitive& p,
    double ox, double oy, double oz,
    double dx, double dy, double dz);

// Пересечение луча со всеми примитивами меша.
// Возвращает БЛИЖАЙШЕЕ пересечение.
// maxT > 0 — ограничение (например, до стены).
PrimHit RaycastMesh(const Mesh& m,
    double ox, double oy, double oz,
    double dx, double dy, double dz,
    double maxT = 0.0);